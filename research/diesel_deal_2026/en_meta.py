EN_TITLE = "The 2026 Russia–US Diesel Deal: Volumes, Benefits and Risks"
EN_ABSTRACT = (
    "On 9 October 2026 the presidents of Russia and the United States agreed on supplies of Russian diesel "
    "fuel to the US and world markets, and the US Treasury issued General License No. 135 allowing such "
    "operations until 7 April 2027. This is the first case since 2022 when the initiator of sanctions "
    "temporarily exempted a large commodity flow. The article estimates the volumes, revenue and fiscal "
    "effect of the deal on the basis of official documents and statistics (OFAC, the Russian Ministry of "
    "Finance, the Bank of Russia, the US Energy Information Administration, the IEA and Kpler). The declared "
    "programme of 4.8 mln tonnes over six months averages 0.8 mln tonnes per month, or 2.67 per cent of "
    "international diesel trade, and covers only 5.0–7.5 per cent of the world deficit in October. Gross "
    "revenue is estimated at USD 4.32–6.72 bn, the increase in budget revenues at RUB 137.4–192.4 bn, or "
    "2.6–3.7 per cent of the federal budget deficit for January–September 2026, which is less than the "
    "October damper payments of RUB 415 bn. The main gain for Russia was not budget revenue but the "
    "legalisation of logistics, insurance and payments. The arrangement is unstable: the licence is limited "
    "in time and product scope, does not repeal the statutory import ban and depends on the US political "
    "cycle. The promised decline in retail prices did not materialise."
)

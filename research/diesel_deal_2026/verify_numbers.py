texts = []
doc = Document(DOCX)
for p in doc.paragraphs:
    texts.append(p.text)
for t in doc.tables:
    for row in t.rows:
        for cell in row.cells:
            texts.append(cell.text)
full = "\n".join(texts)
if "Список литературы" in full:
    full = full.split("Список литературы")[0]   # литература проверяется отдельно
# даты, DOI, годы и ссылки на разделы не являются числовыми утверждениями о сделке
full = re.sub(r"\b\d{2}\.\d{2}\.\d{4}\b", " <DATE> ", full)
full = re.sub(r"\b\d{2}\.\d{2}\b", " <DATE> ", full)
full = re.sub(r"10\.\d{4,5}/\S+", " <DOI> ", full)
full = re.sub(r"\b(19|20)\d{2}\b", " <YEAR> ", full)
full = re.sub(r"\bCFR\b[^.]*", " <CFR> ", full)
full = re.sub(r"(рис|табл|раздел|разделы|соотношени\w*|формул\w*)\s*\(?\d[\d,.–-]*\)?", r"\1 <REF> ", full)

allowed = set()
for k, v in M["formatted"].items():
    if isinstance(v, str):
        allowed.add(v)
        allowed.add(v.replace(",", "."))
for k, v in M["derived"].items():
    if isinstance(v, (int, float)):
        allowed.add(f"{v:g}")
        allowed.add(f"{v:g}".replace(".", ","))
        allowed.add(f"{v:.1f}".replace(".", ","))
        allowed.add(f"{v:.2f}".replace(".", ","))
for v in M["inputs"].values():
    if isinstance(v, (int, float)):
        for fmt_ in ("{:.0f}", "{:.1f}", "{:.2f}", "{:g}"):
            s = fmt_.format(v)
            allowed.add(s)
            allowed.add(s.replace(".", ","))
allowed |= set(STATIC.keys())

found = NUM.findall(full)
unknown = sorted({f for f in found
                  if f not in allowed and not any(f in a for a in allowed)},
                 key=lambda x: (len(x), x))
print("Всего числовых токенов:", len(found), "| уникальных:", len(set(found)))
print("Не сопоставлено (проверить вручную):", len(unknown))
for u in unknown:
    print("   ", u)

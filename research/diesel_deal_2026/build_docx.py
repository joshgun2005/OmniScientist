from sources import SOURCES
_ORDER = {src["key"]: i for i, src in enumerate(SOURCES, 1)}


def _sub(m):
    keys = [k.strip() for k in m.group(1).split(";")]
    nums = []
    for k in keys:
        if k not in _ORDER:
            raise KeyError(f"Источник отсутствует в списке литературы: {k}")
        nums.append(_ORDER[k])
    return "[" + "; ".join(str(n) for n in sorted(nums)) + "]"


def cite(text):
    """[@@key1; key2] -> [n1; n2] по реальному порядку списка литературы."""
    return re.sub(r"\[@@([^\]]+)\]", _sub, text)



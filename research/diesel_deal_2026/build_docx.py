def set_run_font(run, size=14, bold=False, italic=False, name=FONT, color=None):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = RGBColor(*color)
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(qn(attr), name)


def para(doc, text="", size=14, bold=False, italic=False, align="just",
         indent=1.25, before=0, after=0, spacing=1.5, keep=False):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = {"just": WD_ALIGN_PARAGRAPH.JUSTIFY, "center": WD_ALIGN_PARAGRAPH.CENTER,
                    "left": WD_ALIGN_PARAGRAPH.LEFT, "right": WD_ALIGN_PARAGRAPH.RIGHT}[align]
    pf.first_line_indent = Cm(indent) if indent else None
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = spacing
    if keep:
        pf.keep_with_next = True
    if text:
        text = cite(text)
        r = p.add_run(text)
        set_run_font(r, size, bold, italic)
    if text:
        BLOCKS.append({"t": "p", "text": text, "size": size, "bold": bold, "italic": italic,
                       "align": align, "indent": indent, "spacing": spacing,
                       "before": before, "after": after})
    return p


def rich(doc, chunks, size=14, align="just", indent=1.25, before=0, after=0,
         spacing=1.5, keep=False):
    """chunks: список (текст, {'b':..,'i':..,'sub':..,'sup':..})"""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = {"just": WD_ALIGN_PARAGRAPH.JUSTIFY, "center": WD_ALIGN_PARAGRAPH.CENTER,
                    "left": WD_ALIGN_PARAGRAPH.LEFT, "right": WD_ALIGN_PARAGRAPH.RIGHT}[align]
    pf.first_line_indent = Cm(indent) if indent else None
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = spacing
    if keep:
        pf.keep_with_next = True
    for text, style in chunks:
        r = p.add_run(text)
        set_run_font(r, size, style.get("b", False), style.get("i", False))
        if style.get("sub"):
            r.font.subscript = True
        if style.get("sup"):
            r.font.superscript = True
    BLOCKS.append({"t": "runs", "runs": [(t, st) for t, st in chunks], "size": size,
                   "align": align, "indent": indent, "spacing": spacing})
    return p


def heading(doc, text, level=1):
    size = 14
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
    pf.first_line_indent = Cm(1.25) if level > 1 else Cm(0)
    pf.space_before = Pt(16 if level == 1 else 10)
    pf.space_after = Pt(8 if level == 1 else 6)
    pf.line_spacing = 1.5
    pf.keep_with_next = True
    r = p.add_run(text)
    set_run_font(r, size, bold=True)
    BLOCKS.append({"t": "h", "text": text, "level": level})
    return p


def equation(doc, chunks, number):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.first_line_indent = Cm(0)
    pf.space_before = Pt(6)
    pf.space_after = Pt(6)
    pf.line_spacing = 1.5
    pf.tab_stops.add_tab_stop(Cm(8.0), WD_TAB_ALIGNMENT.CENTER)
    pf.tab_stops.add_tab_stop(Cm(16.4), WD_TAB_ALIGNMENT.RIGHT)
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    r0 = p.add_run("\t")
    set_run_font(r0, 14)
    for text, style in chunks:
        r = p.add_run(text)
        set_run_font(r, 14, False, style.get("i", False))
        if style.get("sub"):
            r.font.subscript = True
    r2 = p.add_run("\t(" + number + ")")
    set_run_font(r2, 14)
    BLOCKS.append({"t": "eq", "runs": [(t, st) for t, st in chunks], "number": number})
    return p


def tap(doc, text, size=14, align="center", before=2, after=2, italic=False):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = {"center": WD_ALIGN_PARAGRAPH.CENTER, "left": WD_ALIGN_PARAGRAPH.LEFT,
                    "just": WD_ALIGN_PARAGRAPH.JUSTIFY}[align]
    pf.first_line_indent = Cm(0)
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = 1.15
    r = p.add_run(text)
    set_run_font(r, size, False, italic)
    BLOCKS.append({"t": "cap", "text": text, "size": size, "align": align, "before": before,
                   "after": after})
    return p


def figure(doc, filename, caption, width_cm=15.6):
    p = doc.add_paragraph()
    p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(os.path.join(FIG, filename), width=Cm(width_cm))
    BLOCKS.append({"t": "img", "path": os.path.join(FIG, filename), "width_cm": width_cm})
    tap(doc, caption, size=12, align="just", before=0, after=10)


def table(doc, spec, note=None):
    """spec: dict(widths, rows, header=True)"""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.keep_with_next = True
    p.add_run("")
    t = doc.add_table(rows=0, cols=len(spec["widths"]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for ri, row in enumerate(spec["rows"]):
        cells = t.add_row().cells
        for ci, cell_text in enumerate(row):
            cell = cells[ci]
            cell.width = Cm(spec["widths"][ci])
            cp = cell.paragraphs[0]
            cp.paragraph_format.space_before = Pt(2)
            cp.paragraph_format.space_after = Pt(2)
            cp.paragraph_format.line_spacing = 1.0
            cp.paragraph_format.first_line_indent = Cm(0)
            cp.alignment = WD_ALIGN_PARAGRAPH.LEFT if ci == 0 else WD_ALIGN_PARAGRAPH.CENTER
            r = cp.add_run(str(cell_text))
            set_run_font(r, 12, bold=(ri == 0 and spec.get("header", True)))
    # повтор шапки
    if spec.get("header", True):
        tr = t.rows[0]._tr
        trPr = tr.get_or_add_trPr()
        tblHeader = OxmlElement("w:tblHeader")
        tblHeader.set(qn("w:val"), "true")
        trPr.append(tblHeader)
    BLOCKS.append({"t": "table", "widths": spec["widths"], "rows": spec["rows"]})
    if note:
        tap(doc, note, size=11.5, align="left", before=3, after=8)
    else:
        p2 = doc.add_paragraph()
        p2.paragraph_format.space_after = Pt(6)
        p2.paragraph_format.line_spacing = 1.0
        p2.add_run("")
    return t



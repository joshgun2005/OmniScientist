from sources import SOURCES

BY_KEY = {s["key"]: s for s in SOURCES}
_FIRST_SEEN = []
_ORDER = {}


def _sub(m):
    items = []
    for part in m.group(1).split(";"):
        part = part.strip()
        key, _, pages = part.partition("#")
        key = key.strip()
        if key not in BY_KEY:
            raise KeyError("Источник отсутствует в списке литературы: " + key)
        if key not in _FIRST_SEEN:
            _FIRST_SEEN.append(key)
            _ORDER[key] = len(_FIRST_SEEN)
        n = _ORDER[key]
        items.append((n, f"{n}, {pages.strip()}" if pages else str(n)))
    items.sort(key=lambda x: x[0])
    return "[" + "; ".join(x[1] for x in items) + "]"


def cite(text):
    return re.sub(r"\[@@([^\]]+)\]", _sub, text)

def dot(value):
    """Русская запись числа -> английская (для англоязычного блока)."""
    return str(value).replace("\u00a0", "").replace(" ", "").replace(",", ".")



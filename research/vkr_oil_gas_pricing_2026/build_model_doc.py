def plural(n, one, few, many):
    n = int(n)
    if n % 10 == 1 and n % 100 != 11:
        return one
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return few
    return many


def where_block(d, pairs, after=8):
    """Расшифровка формулы одним абзацем: «где D — ...; Brent — ...».

    Символ набирается курсивом (обозначение величины), индекс — прямым
    начертанием: так же, как в самой формуле. Простой символ задаётся
    строкой «D_it», составной — списком фрагментов.
    """
    chunks = [("где ", {})]
    for i, (sym, text) in enumerate(pairs):
        if isinstance(sym, list):
            chunks.extend(sym)
        else:
            base, _, sub = sym.partition("_")
            chunks.append((base, {"i": True}))
            if sub:
                chunks.append((sub, {"sub": True}))
        chunks.append((" — " + text, {}))
        if i < len(pairs) - 1:
            chunks.append(("; ", {}))
        elif not text.rstrip().endswith("."):
            chunks.append((".", {}))
    d.rich(chunks, indent=1.25, after=after, spacing=1.5)



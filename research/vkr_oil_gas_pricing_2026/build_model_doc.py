def p_add(d, text, keys=None, **kw):
    """Абзац; при наличии ключей — со сноской на источник."""
    if keys:
        d.paragraphs_note = None
        p = d.para(text, **kw)
        note = "; ".join(S.describe(k) if k not in cited else S.short(k)
                         for k in keys)
        for k in keys:
            if k not in cited:
                cited.append(k)
        d.add_footnote(p, note)
        return p
    return d.para(text, **kw)


def num(x, nd=2):
    """Число с русским десятичным разделителем; минус — типографский."""
    return fmt.n(x, nd).replace("-", "\u2212")


def star(p):
    if p < 0.01:
        return "***"
    if p < 0.05:
        return "**"
    if p < 0.10:
        return "*"
    return ""


def sig_text(p):
    if p < 0.01:
        return "значим на уровне 1 %"
    if p < 0.05:
        return "значим на уровне 5 %"
    if p < 0.10:
        return "значим на уровне 10 %"
    return "статистически незначим"


def pv(p):
    """p-значение в принятой в работе записи."""
    if p < 0.001:
        return "менее 0,001"
    return num(p, 3)



def month_word(n):
    """21 месяц / 22 месяца / 25 месяцев."""
    n10, n100 = n % 10, n % 100
    if n10 == 1 and n100 != 11:
        return f"{n} месяц"
    if n10 in (2, 3, 4) and n100 not in (12, 13, 14):
        return f"{n} месяца"
    return f"{n} месяцев"


def period_ru(period):
    """2025-01 — 2026-10 → «январь 2025 г. — октябрь 2026 г.»."""
    months = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль",
              "август", "сентябрь", "октябрь", "ноябрь", "декабрь"]
    parts = [p.strip() for p in period.split("—")]
    out = []
    for part in parts:
        y, m = part.split("-")
        out.append(f"{months[int(m) - 1]} {y} г.")
    return " — ".join(out)


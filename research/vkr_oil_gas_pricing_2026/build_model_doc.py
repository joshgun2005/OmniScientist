def p_add(d, text, keys=None, **kw):
    """Абзац; при наличии ключей — со сноской на источник."""
    if not keys:
        return d.para(text, **kw)
    p = d.para(text, **kw)
    note = "; ".join(S.describe(k) if k not in cited else S.short(k)
                     for k in keys)
    for k in keys:
        if k not in cited:
            cited.append(k)
    d.add_footnote(p, note)
    return p


def num(x, nd=2):
    """Число с русским десятичным разделителем; минус — типографский."""
    return fmt.n(x, nd).replace("-", "\u2212")


def pv(p):
    """p-значение в принятой в работе записи."""
    return "менее 0,001" if p < 0.001 else num(p, 3)


def sig(p):
    return "значим на уровне 1 %" if p < 0.01 else (
        "значим на уровне 5 %" if p < 0.05 else (
            "значим на уровне 10 %" if p < 0.10 else "статистически незначим"))


def month_word(n):
    n10, n100 = n % 10, n % 100
    if n10 == 1 and n100 != 11:
        return f"{n} месяц"
    if n10 in (2, 3, 4) and n100 not in (12, 13, 14):
        return f"{n} месяца"
    return f"{n} месяцев"


def period_ru(period):
    """2025-01 — 2026-10 → «январь 2025 г. — октябрь 2026 г.»."""
    months = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль",
              "август", "сентябрь", "октябрь", "ноябрь", "декабрь"]
    out = []
    for part in (p.strip() for p in period.split("—")):
        y, m = part.split("-")
        out.append(f"{months[int(m) - 1]} {y} г.")
    return " — ".join(out)


def month_ru(m):
    months = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль",
              "август", "сентябрь", "октябрь", "ноябрь", "декабрь"]
    y, mm = m.split("-")
    return f"{months[int(mm) - 1]} {y} г."



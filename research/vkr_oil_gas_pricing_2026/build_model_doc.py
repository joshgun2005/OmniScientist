# ------------------------------------------------------------------ утилиты
def p_add(d, text, keys=None, **kw):
    """Абзац; при наличии ключей — подстрочная сноска на источник."""
    if not keys:
        return d.para(text, **kw)
    p = d.para(text, **kw)
    note = "; ".join(S.full(k) for k in keys)
    for k in keys:
        if k not in cited:
            cited.append(k)
        footnoted[k] = note
    d.add_footnote(p, note)
    return p


def num(x, nd=2):
    """Число с русским десятичным разделителем; минус — типографский."""
    return fmt.n(x, nd).replace("-", "\u2212")


def pv(p):
    return "менее 0,001" if p < 0.001 else num(p, 3)


def sig(p):
    return "значим на уровне 1 %" if p < 0.01 else (
        "значим на уровне 5 %" if p < 0.05 else (
            "значим на уровне 10 %" if p < 0.10 else "статистически незначим"))


def plural(n, one, few, many):
    n = int(n)
    if n % 10 == 1 and n % 100 != 11:
        return one
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return few
    return many


def where_block(d, pairs, after=8):
    """Расшифровка формулы одним абзацем (см. MRDoc.where_mixed)."""
    d.where_mixed(pairs, after=after)


def sym(chunks, text=""):
    """Собрать фрагмент формулы: [("AZ", {"sub": True})] -> ((...), tail)."""
    return [c if isinstance(c, tuple) else (c, {"sub": True}) for c in chunks] \
        + ([(text, {})] if text else [])



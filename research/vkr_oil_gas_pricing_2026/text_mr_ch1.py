# ---------------------------------------------------------------- помощники
def F(f, keys, sep="; "):
    """Текст сноски: первое упоминание — полное описание, далее — отсылка."""
    if getattr(f, "cited", None) is None:
        f.cited, f.cited_log = set(), []
    out = []
    for k in keys:
        full = k not in f.cited
        out.append(S.describe(k) if full else S.short(k))
        f.cited.add(k)
        f.cited_log.append(k)
    return sep.join(out)


def P(f, text, keys=None, **kw):
    if keys:
        return f.para_fn(text, F(f, keys), **kw)
    return f.para(text, **kw)



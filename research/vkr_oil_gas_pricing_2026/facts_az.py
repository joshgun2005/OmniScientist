# -*- coding: utf-8 -*-
"""Контрактные (таможенные) ряды Азербайджана и производные цены.

Источник — декларации Государственного таможенного комитета Азербайджана,
публикуемые агентствами Report, Trend, Interfax, Caspian Barrel. Ряды
накопительные (с начала года), поэтому цена за период получена делением
стоимости на объём. Это контрактная цена, а не биржевая котировка: она
отражает фактические условия сделок, включая формульные привязки,
временные лаги и структуру поставок.

Единицы: объём газа — млрд куб. м, стоимость — млрд долл.;
нефть — млн т, стоимость — млрд долл.
"""
import pandas as pd

# --------------------------------------------------------------- газ
# (период, объём млрд куб. м, стоимость млрд долл., источник)
GAS_CUM = [
    ("2024-12", 25.772, 8.400, "ГТК АР, итоги 2024 г."),
    ("2025-07", 14.4097, 5.269, "ГТК АР, январь–июль 2025"),
    ("2025-08", 16.4530, 5.997, "ГТК АР, январь–август 2025 (расчёт)"),
    ("2025-09", 18.5310, 6.696, "ГТК АР, январь–сентябрь 2025 (расчёт)"),
    ("2025-10", 20.6488, 7.4178, "ГТК АР, январь–октябрь 2025"),
    ("2025-11", 22.8042, 8.1175, "ГТК АР, январь–ноябрь 2025"),
    ("2026-06", 12.4300, 4.1100, "ГТК АР, первое полугодие 2026"),
    ("2026-07", 14.4000, 4.9000, "ГТК АР / ИнфоТЭК, январь–июль 2026"),
    ("2026-08", 16.3780, 5.7110, "ГТК АР, январь–август 2026"),
    ("2026-09", 17.9941, 6.4487, "ГТК АР, январь–сентябрь 2026"),
]

# --------------------------------------------------------------- нефть
OIL_CUM = [
    ("2025-08", 15.9250, 8.396, "ГТК АР, январь–август 2025 (расчёт)"),
    ("2025-11", 22.1320, 11.515, "ГТК АР, январь–ноябрь 2025"),
    ("2026-08", 14.6780, 9.282, "ГТК АР, январь–август 2026"),
]

# 1 млн БТЕ = 28,48 куб. м  ->  1 тыс. куб. м = 35,11 млн БТЕ
MMBTU_PER_1000M3 = 35.11
BBL_PER_T = 7.33


def gas_frame():
    rows = []
    for period, vol, val, src in GAS_CUM:
        usd_1000m3 = val * 1000 / vol          # млрд / млрд куб. м
        rows.append({
            "period": period,
            "volume_bcm": vol,
            "value_bn_usd": val,
            "usd_per_1000m3": round(usd_1000m3, 1),
            "usd_per_mmbtu": round(usd_1000m3 / MMBTU_PER_1000M3, 2),
            "source": src,
        })
    return pd.DataFrame(rows).set_index("period")


def oil_frame():
    rows = []
    for period, vol, val, src in OIL_CUM:
        usd_t = val * 1000 / vol
        rows.append({
            "period": period,
            "volume_mt": vol,
            "value_bn_usd": val,
            "usd_per_t": round(usd_t, 1),
            "usd_per_bbl": round(usd_t / BBL_PER_T, 2),
            "source": src,
        })
    return pd.DataFrame(rows).set_index("period")


def period_brent(start, end):
    """Средняя цена Brent за календарный период (по месячным данным)."""
    df = pd.read_csv("data/brent-monthly.csv")
    df["m"] = pd.to_datetime(df["Date"]).dt.to_period("M")
    s = df.set_index("m")["Price"]
    return float(s[(s.index >= pd.Period(start, "M"))
                   & (s.index <= pd.Period(end, "M"))].mean())



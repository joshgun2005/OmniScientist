        "институциональные события — даты вступления в силу решений "
        "ЕС и Правительства РФ: предельная цена нефти (декабрь 2022 г., "
        "пересмотр в феврале 2026 г.), запрет поставок по механизму "
        "потолка (февраль 2023 г.), регламент о поэтапном отказе от "
        "российского газа (январь 2026 г.), обострение в Ормузском "
        "проливе (октябрь 2026 г.);",
        "контрактные (таможенные) цены экспорта Азербайджана — стоимость и "

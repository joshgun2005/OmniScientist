def appendix(d, v, f):
    D, V = d, v
    f.page_break()
    f.para("ПРИЛОЖЕНИЕ А", size=14, bold=True, align="center", indent=0,
           after=6,
           toc_entry=(1, "ПРИЛОЖЕНИЕ А. Исходные данные для расчётов"))
    f.para("Исходные данные для расчётов", size=14, bold=True,
           align="center", indent=0, after=12)
    f.para(
        "В таблице А.1 приведены помесячные значения расчётной цены нефти "
        "Urals, использованные для расчётов в главе 2 и при построении "
        "рисунка 1.", after=6)

    months = ["январь", "февраль", "март", "апрель", "май", "июнь",
              "июль", "август", "сентябрь", "октябрь"]
    rows = []
    for i, m in enumerate(months):
        val = V[f"ru_urals_2026_{i + 1:02d}"]
        flag = "выше" if val > V["ru_budget_urals_2026"] else "ниже"
        rows.append([str(i + 1), m, fmt.n(val, 2), flag])
    f.table(
        ["№", "Месяц 2026 г.", "Расчётная цена Urals, долл./барр.",
         "Относительно бюджетной отсечки"],
        rows, widths=[1.2, 4.0, 5.2, 5.5],
        caption="Таблица А.1 — Помесячная расчётная цена нефти Urals в 2026 г.",
        note="Источник: составлено автором по данным Минэкономразвития "
             "России [@@minec_urals]. Бюджетная цена отсечения — "
             f"{fmt.n(V['ru_budget_urals_2026'], 0)} долл./барр.",
        size=11)



# --------------------------------------------------------------- упорядочение
_RU = set("АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ")


def _bucket(item):
    """0 — нормативные правовые акты, 1 — русскоязычные, 2 — латиница."""
    if item.get("group") == 0:
        return 0
    return 1 if item["gost"][0].upper() in _RU else 2


def _sort_key(item):
    """Нормативные акты -> русскоязычные -> латиница; внутри — по алфавиту.

    Ключ берётся из самого текста библиографической записи, поэтому порядок
    в списке всегда совпадает с тем, что видит читатель.
    """
    text = item["gost"].lower().replace("ё", "е")
    for ch in "«»\"'()[]—–-.,:/":
        text = text.replace(ch, " ")
    return (_bucket(item), " ".join(text.split()))


SOURCES = sorted(SOURCES_RAW, key=_sort_key)

_KEYS = [s["key"] for s in SOURCES]
assert len(_KEYS) == len(set(_KEYS)), "дубли ключей источников"

ORDER = {s["key"]: i for i, s in enumerate(SOURCES, 1)}


def num(key):
    if key not in ORDER:
        raise KeyError(f"Источник отсутствует в списке литературы: {key}")
    return ORDER[key]


def check_alphabet():
    keys = [_sort_key(s) for s in SOURCES]
    assert keys == sorted(keys), "нарушен алфавитный порядок списка литературы"
    assert len(SOURCES) >= 40, "слишком короткий список литературы"
    return True


